import type { FluidProps } from '../physics/fluid';
import type { Rng } from '../core/rng';

export type ParamValue = number | string | boolean | number[];
export type Params = Record<string, ParamValue>;

/** Physical role of a port – used for validation and line identification training. */
export type PortRole =
  | 'suction-out' // reservoir suction outlet
  | 'pump-inlet'
  | 'pump-outlet'
  | 'supply' // valve pressure inlet (P)
  | 'tank' // return to tank (T)
  | 'work' // actuator / valve work port (A, B)
  | 'pilot'
  | 'drain' // case drain / spring chamber drain
  | 'load-sense'
  | 'return-in' // reservoir return inlet
  | 'drain-in' // reservoir drain inlet
  | 'inline-in'
  | 'inline-out'
  | 'gauge';

export type LineType = 'suction' | 'pressure' | 'return' | 'pilot' | 'case-drain' | 'load-sense' | 'work';

export interface PortDefinition {
  id: string;
  /** Marking stamped on the component body (e.g. "P", "T", "A", "IN"). */
  marking: string;
  label: string;
  role: PortRole;
  description: string;
}

export interface HoseSpec {
  /** inner diameter m */
  innerDiameter: number;
  /** m */
  length: number;
  /** maximum working pressure Pa (SAE style rating). Burst assumed at 4×. */
  workingPressure: number;
  /** Hose or rigid tube */
  construction?: 'hose' | 'tube' | 'suction-hose';
}

export interface PortRef {
  component: string;
  port: string;
}

export interface ConnectionDefinition {
  id: string;
  from: PortRef;
  to: PortRef;
  hose: HoseSpec;
  lineType: LineType;
  label?: string;
  /** Optional colour tag – deliberately NOT used for validation (port markings are authoritative). */
  colorTag?: string;
}

export interface ComponentInstanceDefinition {
  id: string;
  /** Component model type (see component registry). */
  type: string;
  label: string;
  /** Optional link to a catalogue part / specification record. */
  partId?: string;
  params: Params;
  /** Schematic layout position (grid units). */
  layout?: { x: number; y: number; rotation?: number };
}

export interface CircuitDefinition {
  id: string;
  name: string;
  description?: string;
  fluidGrade: string;
  /** Grade specified by the equipment – used for "incorrect fluid" detection. */
  specifiedFluidGrade?: string;
  components: ComponentInstanceDefinition[];
  connections: ConnectionDefinition[];
}

export interface FlowElement {
  id: string;
  owner: string;
  label: string;
  nodes: number[];
  /** Write flow INTO each terminal node (m^3/s) given the global pressure vector. */
  flow(p: Float64Array, out: Float64Array): void;
  dissipative: boolean;
  /** Elements discharging to atmosphere record their loss as external leakage. */
  external?: boolean;
}

export interface FluidState {
  temperature: number;
  /** Entrained air volume fraction (0..1). */
  airFraction: number;
  /** Particulate contamination index ≈ ISO 4406 ">4 µm" code (e.g. 16 = clean, 22 = dirty). */
  contamination: number;
  /** Water content ppm */
  water: number;
  /** Ferrous wear-debris index (0 = none, 1 = severe) generated by failing components. */
  wearDebris: number;
  grade: string;
}

export interface SimEvent {
  time: number;
  level: 'info' | 'warning' | 'alarm';
  source: string;
  code: string;
  message: string;
}

export interface FaultQuery {
  /** Effective (currently active) severity 0..1 of a fault kind on a target. */
  severity(target: string, kind: string): number;
}

export interface StepEnv {
  dt: number;
  time: number;
  fluid: FluidProps;
  fluidState: FluidState;
  faults: FaultQuery;
  rng: Rng;
  ambient: number;
  pressure(node: number): number;
  /** Net element flow into a node after the solve (m^3/s) – used by boundary components. */
  inflow(node: number): number;
  log(e: Omit<SimEvent, 'time'>): void;
}

export interface Readout {
  key: string;
  label: string;
  value: number | string | boolean;
  quantity?: import('../core/units').Quantity;
}

export interface RuntimeComponent {
  id: string;
  type: string;
  label: string;
  def: ComponentInstanceDefinition;
  elements: FlowElement[];
  portNodes: Record<string, number>;
  inputs: Record<string, number>;
  preStep?(env: StepEnv): void;
  postStep?(env: StepEnv): void;
  getState(): Record<string, number>;
  setState(s: Record<string, number>): void;
  readouts(env: StepEnv): Readout[];
  /** Heat (W) generated inside the component not captured by element Q·Δp (e.g. pump mechanical loss). */
  extraHeat?(env: StepEnv): number;
  /** Heat rejected (W) by the component (coolers). */
  heatRejection?(env: StepEnv): number;
}

export interface NodeInfo {
  id: string;
  label: string;
  volume: number;
  /** null = free node solved by the network; otherwise fixed pressure source. */
  boundary: null | (() => number);
  kind: 'port' | 'internal' | 'tank' | 'atmosphere';
  owner: string;
}
